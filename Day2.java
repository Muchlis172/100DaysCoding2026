public class Day2 {
    public static void main(String[] args) {

        // Menggunakan print() untuk mencetak teks tanpa berpindah kebaris baru
        System.out.print("=== ");
        System.out.print(" BIODATA ");
        System.out.print("===\n");

        // Menggunakan println() untuk mencetak teks yg akan otomatis ke baris baru
        System.out.println("Nama Lengkap  : Ahmad Muchlis");
        System.out.println("Alamat        : Baru, Kec.Luyo");

        // Menggunakan printf() untuk mencetak teks dengan format tertentu
        System.out.printf("Tinggi %f cm dan berat %d kg", 172.5, 65);
    }
}
