public class Day27 {
    public static void main(String[] args) {
        
        int angka = 5;
        
        System.out.println("Nilai awal: " + angka);
       
        angka++; 
        System.out.println("Setelah angka++: " + angka);  
        
        ++angka; 
        System.out.println("Setelah ++angka: " + angka);
        
        angka--; 
        System.out.println("Setelah angka--: " + angka);
       
        --angka; 
        System.out.println("Setelah --angka: " + angka); 
    }
}
